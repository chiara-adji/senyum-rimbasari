/** Perbesar gambar 2× dengan EPX/Scale2x per warna (cara yang sama dengan teks HD): diagonal halus, tepi tetap tajam. */
function epxImg(src){const w=src.width,h=src.height,d=src.getContext('2d').getImageData(0,0,w,h).data;
  const g=(x,y)=>{if(x<0||y<0||x>=w||y>=h)return -1;const i=(y*w+x)*4;return d[i+3]<128?-1:(d[i]<<16)|(d[i+1]<<8)|d[i+2];};
  const[c,x]=cv(w*2,h*2);const put=(X,Y,v)=>{if(v<0)return;x.fillStyle='#'+v.toString(16).padStart(6,'0');x.fillRect(X,Y,1,1);};
  for(let j=0;j<h;j++)for(let i=0;i<w;i++){const P0=g(i,j),A=g(i,j-1),B=g(i+1,j),C=g(i-1,j),D=g(i,j+1);
    put(2*i,2*j,C===A&&C!==D&&A!==B?A:P0);put(2*i+1,2*j,A===B&&A!==C&&B!==D?B:P0);
    put(2*i,2*j+1,D===C&&D!==B&&C!==A?C:P0);put(2*i+1,2*j+1,B===D&&B!==A&&D!==C?D:P0);}
  return c;}
